    public static GiftStoreAdapter.GiftStoreItem findGiftBySvga(String svgaPath) {
        if (svgaPath == null || svgaPath.trim().isEmpty()) return null;
        String cleanSvga = svgaPath.trim().toLowerCase();
        if (cleanSvga.startsWith("gift/")) {
            cleanSvga = cleanSvga.substring(5);
        }
        if (cleanSvga.endsWith(".svga")) {
            cleanSvga = cleanSvga.substring(0, cleanSvga.length() - 5);
        }

        for (GiftStoreAdapter.GiftStoreItem item : getAllGifts()) {
            if (item.svgaPath != null && !item.svgaPath.trim().isEmpty()) {
                String itemSvga = item.svgaPath.trim().toLowerCase();
                if (itemSvga.startsWith("gift/")) itemSvga = itemSvga.substring(5);
                if (itemSvga.endsWith(".svga")) itemSvga = itemSvga.substring(0, itemSvga.length() - 5);

                if (itemSvga.equalsIgnoreCase(cleanSvga)) {
                    return item;
                }
            }
        }
        return null;
    }

    public static GiftStoreAdapter.GiftStoreItem findGiftByName(String rawName) {
        if (rawName == null || rawName.trim().isEmpty()) return null;
        String cleanName = rawName.trim();

        // Direct exact match or regex strip "(x2)", "(Targeted)" etc.
        String baseName = cleanName.replaceAll("\\s*\\(.*?\\)", "").trim();

        for (GiftStoreAdapter.GiftStoreItem item : getAllGifts()) {
            if (item.name.equalsIgnoreCase(cleanName) || item.name.equalsIgnoreCase(baseName)) {
                return item;
            }
        }

        // Substring matching
        for (GiftStoreAdapter.GiftStoreItem item : getAllGifts()) {
            if (baseName.toLowerCase().contains(item.name.toLowerCase()) || item.name.toLowerCase().contains(baseName.toLowerCase())) {
                return item;
            }
        }

        // SVGA filename match fallback
        return findGiftBySvga(cleanName);
    }

    public static GiftStoreAdapter.GiftStoreItem findGiftByAny(String rawName, String svgaPath) {
        GiftStoreAdapter.GiftStoreItem matched = findGiftByName(rawName);
        if (matched != null) return matched;
        return findGiftBySvga(svgaPath);
    }
